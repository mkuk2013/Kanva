-- ============================================================
-- KANVA v3 — Supabase schema (run once in Supabase SQL Editor)
-- Auth is handled by Supabase Auth (email/password + Google).
-- This schema stores app data keyed by the user's auth id.
-- ============================================================

-- Profiles: one row per user (plan, admin flags)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique not null,
  name text,
  picture text,
  plan text not null default 'free',          -- 'free' | 'pro'
  blocked boolean not null default false,
  created_at timestamptz not null default now()
);

-- Designs: full canvas JSON + thumbnail per design
create table if not exists public.designs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null default 'Untitled design',
  size_id text, size_name text, size_w int, size_h int,
  data jsonb not null,                        -- { json, bg, thumb }
  trashed boolean not null default false,
  updated_at timestamptz not null default now()
);
create index if not exists designs_user_idx on public.designs(user_id);

-- Teams: Pro owner -> member emails (member gets Pro while listed)
create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  owner_email text not null,
  member_email text not null,
  member_name text,
  role text not null default 'Editor',
  created_at timestamptz not null default now(),
  unique(owner_id, member_email)
);

-- Orders: Easypaisa manual payments (pending -> approved/rejected)
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  email text not null,
  plan text not null,                          -- 'monthly' | 'yearly'
  amount int not null,
  tid text not null,
  screenshot text,                             -- data URL (small) or null
  status text not null default 'pending',      -- 'pending' | 'approved' | 'rejected'
  created_at timestamptz not null default now()
);

-- Brand kits
create table if not exists public.brand_kits (
  user_id uuid primary key references auth.users(id) on delete cascade,
  data jsonb not null default '{"colors":[],"logo":"","font":"Poppins"}'
);

-- ============ Row Level Security ============
alter table public.profiles  enable row level security;
alter table public.designs   enable row level security;
alter table public.teams     enable row level security;
alter table public.orders    enable row level security;
alter table public.brand_kits enable row level security;

-- Helper: is the caller the super admin?
create or replace function public.is_admin() returns boolean
language sql stable as $$
  select coalesce(auth.jwt() ->> 'email', '') = 'mkuk2013@gmail.com'
$$;

-- Profiles: own row read/write; admin reads/updates all
create policy "profiles own read"   on public.profiles for select using (auth.uid() = id or public.is_admin());
create policy "profiles own upsert" on public.profiles for insert with check (auth.uid() = id);
create policy "profiles own update" on public.profiles for update using (auth.uid() = id or public.is_admin());
create policy "profiles admin delete" on public.profiles for delete using (public.is_admin());

-- Designs: strictly per-user; admin can read all (support)
create policy "designs own all" on public.designs for all
  using (auth.uid() = user_id or public.is_admin())
  with check (auth.uid() = user_id);

-- Teams: owner manages own team; members can read rows where they are the member
create policy "teams owner all" on public.teams for all
  using (auth.uid() = owner_id or public.is_admin())
  with check (auth.uid() = owner_id);
create policy "teams member read" on public.teams for select
  using (member_email = (auth.jwt() ->> 'email'));

-- Orders: user creates/reads own; admin reads all + updates status
create policy "orders own insert" on public.orders for insert with check (auth.uid() = user_id);
create policy "orders own read"   on public.orders for select using (auth.uid() = user_id or public.is_admin());
create policy "orders admin update" on public.orders for update using (public.is_admin());

-- Brand kits: per-user
create policy "brand own all" on public.brand_kits for all
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Auto-create a profile row when a new auth user signs up
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, name, picture)
  values (new.id, new.email,
          coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)),
          new.raw_user_meta_data ->> 'avatar_url')
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
